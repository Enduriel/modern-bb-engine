//! macOS: keys as CEF wants them there. CEF builds an `NSEvent` from a key event's
//! native key code (a `kVK_*` virtual key) and characters, and Chromium takes the page's
//! `keyCode` from those, not from the Windows code the event carries. So each Windows
//! virtual-key code is given its Mac key and the characters it types (unshifted).

/// The Mac virtual key (`kVK_*`, Carbon's `Events.h`) for the Windows virtual-key code
/// `vk`, and the character the key types without modifiers (AppKit's function-key
/// characters for keys that type none), if the Mac has it.
pub(super) fn mac_key(vk: i32) -> Option<(i32, u16)> {
	/// The letters' keys, `A` to `Z`.
	const LETTERS: [i32; 26] = [
		0x00, 0x0B, 0x08, 0x02, 0x0E, 0x03, 0x05, 0x04, 0x22, 0x26, 0x28, 0x25, 0x2E, 0x2D, 0x1F, 0x23, 0x0C, 0x0F, 0x01, 0x11, 0x20,
		0x09, 0x0D, 0x07, 0x10, 0x06,
	];
	/// The digits' keys, `0` to `9`.
	const DIGITS: [i32; 10] = [0x1D, 0x12, 0x13, 0x14, 0x15, 0x17, 0x16, 0x1A, 0x1C, 0x19];
	/// F1 to F12, and their AppKit characters (`NSF1FunctionKey`…).
	const FUNCTION: [i32; 12] = [0x7A, 0x78, 0x63, 0x76, 0x60, 0x61, 0x62, 0x64, 0x65, 0x6D, 0x67, 0x6F];
	/// The keypad's digits, `0` to `9`.
	const KEYPAD: [i32; 10] = [0x52, 0x53, 0x54, 0x55, 0x56, 0x57, 0x58, 0x59, 0x5B, 0x5C];
	let key = match vk {
		0x41..=0x5A => (LETTERS[(vk - 0x41) as usize], (vk as u16) + 0x20),
		0x30..=0x39 => (DIGITS[(vk - 0x30) as usize], vk as u16),
		0x70..=0x7B => (FUNCTION[(vk - 0x70) as usize], 0xF704 + (vk - 0x70) as u16),
		0x60..=0x69 => (KEYPAD[(vk - 0x60) as usize], (vk - 0x30) as u16),
		0x08 => (0x33, 0x7F),
		0x09 => (0x30, 0x09),
		0x0D => (0x24, 0x0D),
		0x1B => (0x35, 0x1B),
		0x20 => (0x31, 0x20),
		0x21 => (0x74, 0xF72C),
		0x22 => (0x79, 0xF72D),
		0x23 => (0x77, 0xF72B),
		0x24 => (0x73, 0xF729),
		0x25 => (0x7B, 0xF702),
		0x26 => (0x7E, 0xF700),
		0x27 => (0x7C, 0xF703),
		0x28 => (0x7D, 0xF701),
		0x2D => (0x72, 0xF727),
		0x2E => (0x75, 0xF728),
		0x10 => (0x38, 0),
		0x11 => (0x3B, 0),
		0x12 => (0x3A, 0),
		0x14 => (0x39, 0),
		0x5B => (0x37, 0),
		0x6A => (0x43, u16::from(b'*')),
		0x6B => (0x45, u16::from(b'+')),
		0x6D => (0x4E, u16::from(b'-')),
		0x6E => (0x41, u16::from(b'.')),
		0x6F => (0x4B, u16::from(b'/')),
		0xBA => (0x29, u16::from(b';')),
		0xBB => (0x18, u16::from(b'=')),
		0xBC => (0x2B, u16::from(b',')),
		0xBD => (0x1B, u16::from(b'-')),
		0xBE => (0x2F, u16::from(b'.')),
		0xBF => (0x2C, u16::from(b'/')),
		0xC0 => (0x32, u16::from(b'`')),
		0xDB => (0x21, u16::from(b'[')),
		0xDC => (0x2A, u16::from(b'\\')),
		0xDD => (0x1E, u16::from(b']')),
		0xDE => (0x27, u16::from(b'\'')),
		_ => return None,
	};
	Some(key)
}

#[cfg(test)]
mod tests {
	use super::*;

	#[test]
	fn letters_digits_and_named_keys() {
		assert_eq!(mac_key(0x41), Some((0x00, u16::from(b'a'))));
		assert_eq!(mac_key(0x42), Some((0x0B, u16::from(b'b'))));
		assert_eq!(mac_key(0x5A), Some((0x06, u16::from(b'z'))));
		assert_eq!(mac_key(0x30), Some((0x1D, u16::from(b'0'))));
		assert_eq!(mac_key(0x35), Some((0x17, u16::from(b'5'))));
		assert_eq!(mac_key(0x0D), Some((0x24, 0x0D)));
		assert_eq!(mac_key(0x26), Some((0x7E, 0xF700)));
		assert_eq!(mac_key(0x7B), Some((0x6F, 0xF70F)));
		assert_eq!(mac_key(0xFF), None);
	}
}
